#!/usr/bin/env python3
"""Expected values for the unit tests of js/stats.js, computed with numpy, scipy and statsmodels (Holm).

Writes js/stats.test-data.js, which js/stats.test.html compares against the JavaScript implementation
(open it from a local server: python3 -m http.server -d web, then /js/stats.test.html). Re-run after
adding cases:

    python3 web/tools/stats_fixtures.py
"""
import json
from pathlib import Path

import numpy as np
from scipy import stats
from scipy.special import betainc
from statsmodels.stats.multitest import multipletests

OUT = Path(__file__).resolve().parent.parent / "js" / "stats.test-data.js"

SAMPLES = {
    "control": [42.1, 40.3, 44.8, 41.7],
    "treatA": [30.2, 28.9, 33.5],
    "treatB": [39.0, 43.2, 41.1, 38.4, 40.0],
    "tiny": [12.0, 12.5],
    "wide": [5.0, 60.0, 33.0, 21.0, 48.0, 15.0],
    "extreme": [90.0, 90.1, 89.9, 90.05],
}

WELCH = [("treatA", "control"), ("treatB", "control"), ("tiny", "control"), ("wide", "treatA"), ("control", "extreme")]
ANOVA = [["control", "treatA", "treatB"], ["control", "treatB"], ["control", "treatA", "treatB", "wide", "tiny"], ["control", "extreme"]]
T_CDF = [(-3.2, 2), (0.0, 5), (0.7, 1), (1.96, 1000), (2.5, 3.7), (-1.1, 12.25), (8.0, 4), (25.0, 2.3)]
T_PPF = [(0.975, 1), (0.975, 2), (0.975, 4), (0.975, 9.5), (0.975, 30), (0.995, 5), (0.9, 200), (0.025, 3)]
F_SF = [(3.5, 2, 9), (0.4, 1, 6), (12.0, 3, 20), (150.0, 2, 8), (1.0, 4, 4), (2.2, 7, 3.5)]
BETAINC = [(0.3, 2.0, 5.0), (0.9, 0.5, 0.5), (0.01, 10.0, 3.0), (0.6, 7.5, 2.25)]
HOLM = [[0.01, 0.04, 0.03, 0.005], [0.2, 0.01], [0.04, 0.04, 0.04], [0.001, 0.9, 0.02, 0.5, 0.03]]


def main():
    s = {k: np.array(v) for k, v in SAMPLES.items()}
    out = {"samples": SAMPLES, "describe": {}, "welch": [], "anova": [], "tCdf": [], "tPpf": [], "fSf": [], "betaInc": [], "holm": []}
    for k, x in s.items():
        n = len(x)
        m, sd = x.mean(), x.std(ddof=1)
        sem = stats.sem(x)
        lo, hi = stats.t.interval(0.95, n - 1, loc=m, scale=sem)
        out["describe"][k] = {"n": n, "mean": m, "sd": sd, "sem": sem, "ciLow": lo, "ciHigh": hi}
    for a, b in WELCH:
        r = stats.ttest_ind(s[a], s[b], equal_var=False)
        out["welch"].append({"a": a, "b": b, "t": r.statistic, "df": r.df, "p": r.pvalue})
    for names in ANOVA:
        r = stats.f_oneway(*[s[n] for n in names])
        k, N = len(names), sum(len(s[n]) for n in names)
        out["anova"].append({"groups": names, "F": r.statistic, "df1": k - 1, "df2": N - k, "p": r.pvalue})
    out["tCdf"] = [{"t": t, "df": df, "p": stats.t.cdf(t, df)} for t, df in T_CDF]
    out["tPpf"] = [{"p": p, "df": df, "t": stats.t.ppf(p, df)} for p, df in T_PPF]
    out["fSf"] = [{"f": f, "d1": d1, "d2": d2, "p": stats.f.sf(f, d1, d2)} for f, d1, d2 in F_SF]
    out["betaInc"] = [{"x": x, "a": a, "b": b, "v": betainc(a, b, x)} for x, a, b in BETAINC]
    for ps in HOLM:
        out["holm"].append({"p": ps, "adj": list(multipletests(ps, method="holm")[1])})
    conv = lambda o: float(o) if isinstance(o, (np.floating, np.integer)) else o  # noqa: E731
    text = json.dumps(out, default=conv)
    OUT.write_text("// Generated by tools/stats_fixtures.py (numpy/scipy): expected values for stats.test.js. Do not edit.\n"
                   f"export const FIXTURES = {text};\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
